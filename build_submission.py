"""Bundle the bot + its lookup tables into ONE self-contained file: submission.py.
Run after calibrate.py / pushfold_cfr.py:   python build_submission.py
Then paste the starter kit's Agent wrapper at the bottom (see ADAPTER below).
"""
import base64, os, pickle, re, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
MODULES = ["cards", "features", "icm", "opponent", "agent"]
LOCAL = re.compile(r"^\s*(from (%s) import .*|import (%s))\s*$" % ("|".join(MODULES), "|".join(MODULES)))

ADAPTER = '''
# ============================================================ ADAPTER (edit on the day)
# Map the starter kit's observation object to the dict Agent.act() expects:
#   hole, board (card ints, rank*4+suit, rank 0=2..12=A, suit 0..3 = c,d,h,s), street (0..3),
#   seat, button, sb, bb, stacks (chips behind, per seat), bets (this street, per seat),
#   in_hand, allin, alive (bools per seat), pot (incl. current bets), to_call, current_bet,
#   min_raise_to, max_raise_to, legal (subset of fold/check/call/raise),
#   history [(seat, street, action, amount_to)], hand_no, points (per finishing place, 1st first)
_BOT = None
def _bot():
    global _BOT
    if _BOT is None:
        _BOT = Agent(seed=1)
    return _BOT
'''


def main():
    out = ["# AUTO-GENERATED by build_submission.py. Do not edit by hand.\n"]
    blobs = {}
    for name in ("tables.pkl", "pushfold.pkl"):
        with open(os.path.join(HERE, name), "rb") as f:
            blobs[name] = base64.b64encode(zlib.compress(f.read(), 9)).decode()
    out.append("import base64 as _b64, zlib as _zlib, pickle as _pickle\n")
    out.append("_BLOBS = {%s}\n" % ", ".join("%r: %r" % kv for kv in blobs.items()))
    for m in MODULES:
        src = open(os.path.join(HERE, m + ".py")).read()
        src = re.sub(r"^from (%s) import \([^)]*\)\n" % "|".join(MODULES), "", src, flags=re.M)
        lines = [l for l in src.splitlines() if not LOCAL.match(l)]
        src = "\n".join(lines)
        if m == "agent":
            src = re.sub(r"def _load\(name\):\n(    .*\n)+",
                         "def _load(name):\n    return _pickle.loads(_zlib.decompress(_b64.b64decode(_BLOBS[name])))\n",
                         src + "\n", count=1)
        if m == "cards":
            src = src.replace("from itertools import combinations", "from itertools import combinations")
        out.append("\n# ---------------------------------------------------------------- %s.py\n" % m)
        out.append(src + "\n")
    out.append(ADAPTER)
    path = os.path.join(HERE, "submission.py")
    with open(path, "w") as f:
        f.write("".join(out))
    print("wrote submission.py (%.1f KB)" % (os.path.getsize(path) / 1024))


if __name__ == "__main__":
    main()
